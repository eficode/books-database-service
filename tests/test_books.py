def test_upload_cover_unsupported_format(mock_db_session):
    mock_db_session.query.return_value.filter.return_value.first.return_value = Book(id=1, title="Test Book", author="Test Author", pages=100)
    file = io.BytesIO(b"dummy content")
    response = client.post("/books/1/cover", files={"file": ("test.txt", file, "text/plain")})
    assert response.status_code == 400
    assert response.json().get("detail") == "Unsupported file format"


def test_upload_cover_file_too_large(mock_db_session):
    mock_db_session.query.return_value.filter.return_value.first.return_value = Book(id=1, title="Test Book", author="Test Author", pages=100)
    file = io.BytesIO(b"dummy content" * (5 * 1024 * 1024 + 1))
    response = client.post("/books/1/cover", files={"file": ("test.jpg", file, "image/jpeg")})
    assert response.status_code == 400
    assert response.json().get("detail") == "The file size is too large"


def test_upload_cover_network_failure(mock_db_session):
    mock_db_session.query.return_value.filter.return_value.first.return_value = Book(id=1, title="Test Book", author="Test Author", pages=100)
    file = io.BytesIO(b"dummy content")
    with patch("fastapi_demo.utils.simulate_network_failure", return_value=True):
        response = client.post("/books/1/cover", files={"file": ("test.jpg", file, "image/jpeg")})
    assert response.status_code == 503
    assert response.json().get("detail") == "Upload failed due to network issues"


